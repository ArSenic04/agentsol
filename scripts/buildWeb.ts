/**
 * Builds the website into dist/web (or --out <dir>):
 *  - transpiles web/src/*.ts to browser ES modules (type-only imports are erased),
 *  - copies index.html, styles.css and favicon.svg,
 *  - records the synthetic demo: runs the real core on a throwaway copy of the demo
 *    fixture and stores the exact API responses the local bridge would return.
 * The output is static and contains no API server; refuses to finish if it finds
 * absolute local paths or unredacted sample secrets in what it wrote.
 */
import { existsSync, readdirSync } from "node:fs";
import { copyFile, mkdir, mkdtemp, readFile, readdir, realpath, rm, writeFile } from "node:fs/promises";
import { homedir, tmpdir } from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";
import ts from "typescript";
import { validateProjectRoot } from "../src/core/projectRoots.ts";
import { createAssistantService } from "../src/core/service/assistant.ts";
import { WorkspaceStore } from "../src/core/store.ts";
import { handleApi } from "../src/web/api.ts";
import { DEMO_FILES } from "./demoFixture.ts";

const REPO = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const BUILD_MARKER = ".agentlore-web-build";
const LEGACY_BUILD_MARKER = ".agentweave-web-build"; // builds made before the rename
export const SCOPE_TARGETS = ["services/api/handler.ts", "src/index.ts", "skills/changelog/SKILL.md"];
const PLATFORMS = ["claude-code", "codex", "cursor"];

function parseOut(argv: string[]): string {
  const i = argv.indexOf("--out");
  return path.resolve(i >= 0 ? (argv[i + 1] ?? "") : path.join(REPO, "dist", "web"));
}

async function prepareOut(out: string): Promise<void> {
  if (existsSync(out)) {
    const entries = readdirSync(out);
    if (entries.length > 0 && !entries.includes(BUILD_MARKER) && !entries.includes(LEGACY_BUILD_MARKER)) throw new Error(`${out} is not empty and is not an earlier web build; refusing to delete it`);
    await rm(out, { recursive: true, force: true });
  }
  await mkdir(path.join(out, "js"), { recursive: true });
  await writeFile(path.join(out, BUILD_MARKER), "Generated by npm run web:build. Safe to delete.\n");
}

async function transpile(out: string): Promise<void> {
  const srcDir = path.join(REPO, "web", "src");
  for (const name of await readdir(srcDir)) {
    if (!name.endsWith(".ts") || name.endsWith(".d.ts")) continue;
    const input = await readFile(path.join(srcDir, name), "utf8");
    const r = ts.transpileModule(input, {
      fileName: name,
      reportDiagnostics: true,
      compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.ESNext, verbatimModuleSyntax: true, rewriteRelativeImportExtensions: true, sourceMap: false, removeComments: false },
    });
    if (r.diagnostics && r.diagnostics.length > 0) throw new Error(`transpile failed for ${name}: ${ts.flattenDiagnosticMessageText(r.diagnostics[0]?.messageText ?? "", "\n")}`);
    await writeFile(path.join(out, "js", name.replace(/\.ts$/, ".js")), r.outputText);
  }
  for (const f of ["index.html", "styles.css", "favicon.svg"]) await copyFile(path.join(REPO, "web", f), path.join(out, f));
}

type Recorded = { status: number; body: unknown };

/** Runs the real core on a throwaway synthetic project and records API responses. */
export async function recordDemo(): Promise<{ builtAt: string; responses: Record<string, Recorded>; scopeTargets: string[] }> {
  const base = await realpath(await mkdtemp(path.join(tmpdir(), "agentlore-webdemo-")));
  const projectDir = path.join(base, "project");
  const wsDir = path.join(base, "workspace");
  try {
    for (const [rel, content] of Object.entries(DEMO_FILES)) {
      const abs = path.join(projectDir, rel);
      await mkdir(path.dirname(abs), { recursive: true });
      await writeFile(abs, content, { flag: "wx" });
    }
    const store = WorkspaceStore.open(wsDir);
    try {
      const root = await validateProjectRoot({ candidate: projectDir, homeReal: await realpath(homedir()), workspaceDir: wsDir });
      if (!root.ok) throw new Error(root.error);
      const projectId = store.addProject({ name: "paper-lantern-demo", rootReal: root.value }).id;
      const svc = createAssistantService(store, { reporter: () => "assistant:demo-script", onInternalError: (op, e) => { throw new Error(`${op}: ${String(e)}`); } });
      const must = <T>(r: { ok: true; value: T } | { ok: false; error: { message: string } }): T => {
        if (!r.ok) throw new Error(r.error.message);
        return r.value;
      };
      must(await svc.scan({ projectId }));
      const listed = must(svc.listSources({ projectId }));
      const rootSrc = listed.sources.find((s) => s.relPath === "AGENTS.md");
      const apiSrc = listed.sources.find((s) => s.relPath === "services/api/AGENTS.md");
      if (!rootSrc || !apiSrc) throw new Error("demo fixture changed: expected AGENTS.md and services/api/AGENTS.md");
      const rootRead = must(svc.readSource({ sourceId: rootSrc.sourceId }));
      const apiRead = must(svc.readSource({ sourceId: apiSrc.sourceId }));
      // Prewritten by this script (not an AI), exactly like `npm run demo`.
      const submitted = must(svc.submitFindings({
        projectId,
        findings: [{
          checkId: "S01", title: "Package manager differs", severity: "info", confidence: "medium",
          message: "The root says npm and services/api says pnpm. This may be intended layering; confirm which applies in services/api.",
          evidence: [
            { sourceId: rootSrc.sourceId, versionId: rootRead.versionId, startLine: 3, endLine: 3, quote: "- Use npm to run scripts." },
            { sourceId: apiSrc.sourceId, versionId: apiRead.versionId, startLine: 3, endLine: 3, quote: "- Use pnpm to run scripts in this package." },
          ],
        }],
      }));
      must(svc.proposeChange({
        projectId, sourceId: rootSrc.sourceId, baseVersionId: rootRead.versionId, findingIds: submitted.accepted,
        rationale: "Say explicitly that services/api uses pnpm.",
        edits: [{ startLine: 3, endLine: 3, expectedText: "- Use npm to run scripts.", replacementLines: ["- Use npm to run scripts (services/api uses pnpm)."] }],
      }));

      const enc = encodeURIComponent;
      const urls = ["/api/status", ...["sources", "findings", "freshness", "proposals"].map((k) => `/api/projects/${enc(projectId)}/${k}`)];
      for (const s of listed.sources) urls.push(`/api/sources/${enc(s.sourceId)}`);
      for (const t of SCOPE_TARGETS) for (const p of PLATFORMS) urls.push(`/api/projects/${enc(projectId)}/scope?target=${enc(t)}&platform=${enc(p)}`);
      const responses: Record<string, Recorded> = {};
      for (const u of urls) {
        const url = new URL(u, "http://127.0.0.1");
        responses[u] = await handleApi(svc, url.pathname.slice("/api/".length).split("/").filter(Boolean), url.searchParams);
      }
      return { builtAt: new Date().toISOString(), responses, scopeTargets: SCOPE_TARGETS };
    } finally {
      store.close();
    }
  } finally {
    await rm(base, { recursive: true, force: true });
  }
}

/** Fails the build if output mentions local absolute paths or the fixture's fake secret. */
export async function auditOutput(out: string, forbidden: string[]): Promise<string[]> {
  const problems: string[] = [];
  const walk = async (dir: string): Promise<void> => {
    for (const name of await readdir(dir, { withFileTypes: true })) {
      const abs = path.join(dir, name.name);
      if (name.isDirectory()) await walk(abs);
      else {
        const text = await readFile(abs, "utf8");
        for (const f of forbidden) if (f && text.includes(f)) problems.push(`${path.relative(out, abs)} contains a forbidden string`);
        if (/\/(Users|home|private\/var|var\/folders)\//.test(text)) problems.push(`${path.relative(out, abs)} contains an absolute local path`);
        if (/sk-[A-Za-z0-9]{12,}/.test(text)) problems.push(`${path.relative(out, abs)} contains a secret-like token`);
        if (/<script[^>]+src=["']https?:|<link[^>]+href=["']https?:|@import\s+url\(["']?https?:/i.test(text)) problems.push(`${path.relative(out, abs)} loads an external resource`);
      }
    }
  };
  await walk(out);
  return problems;
}

async function main(): Promise<void> {
  const out = parseOut(process.argv.slice(2));
  await prepareOut(out);
  await transpile(out);
  const demo = await recordDemo();
  await writeFile(path.join(out, "js", "demo-data.js"), `// Recorded by npm run web:build from a synthetic fixture. Not live data.\nexport default ${JSON.stringify(demo)};\n`);
  const problems = await auditOutput(out, [REPO, homedir(), await realpath(tmpdir())]);
  if (problems.length > 0) {
    await rm(out, { recursive: true, force: true });
    throw new Error(`build output failed the privacy audit and was deleted:\n  ${problems.join("\n  ")}`);
  }
  const files = (await readdir(out, { recursive: true })).filter((f) => !f.startsWith("."));
  process.stdout.write(`Built ${files.length} entries into ${path.relative(REPO, out) || out} (static; no API server inside). Privacy audit passed.\n`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  main().catch((e: unknown) => {
    process.stderr.write(`web:build: ${e instanceof Error ? e.message : String(e)}\n`);
    process.exitCode = 1;
  });
}
