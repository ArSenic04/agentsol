/**
 * Compiles the CLI, MCP server and core (src/core, src/cli, src/mcp) to plain JavaScript in
 * build/, so the installed package never runs TypeScript or repo paths. The web bridge is
 * not part of the package. Refuses to delete a build/ it did not create.
 */
import { spawnSync } from "node:child_process";
import { existsSync, readdirSync } from "node:fs";
import { rm, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const REPO = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const OUT = path.join(REPO, "build");
const MARKER = ".agentweave-package-build";

if (existsSync(OUT)) {
  if (!existsSync(path.join(OUT, MARKER)) && readdirSync(OUT).length > 0) {
    process.stderr.write("build/ exists and was not created by npm run build; refusing to delete it\n");
    process.exit(1);
  }
  await rm(OUT, { recursive: true, force: true });
}
const tsc = path.join(REPO, "node_modules", "typescript", "bin", "tsc");
const r = spawnSync(process.execPath, [tsc, "-p", path.join(REPO, "tsconfig.build.json")], { stdio: "inherit" });
if (r.status !== 0) process.exit(r.status ?? 1);
await writeFile(path.join(OUT, MARKER), "Generated by npm run build. Safe to delete.\n");
const count = (dir: string): number => readdirSync(dir, { withFileTypes: true }).reduce((n, e) => n + (e.isDirectory() ? count(path.join(dir, e.name)) : e.name.endsWith(".js") ? 1 : 0), 0);
process.stdout.write(`Compiled ${count(OUT)} JavaScript files into build/\n`);
